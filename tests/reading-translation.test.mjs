import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {loadTypeScript} from './load-typescript.mjs';
const {resolveTerm,findTerm,termsInSelection}=await loadTypeScript('../lib/term-lookup.ts');
const {buildCourseTranslationIndex,readingTranslation}=await loadTypeScript('../lib/cms-translation.ts');
const dictionary=JSON.parse(readFileSync(new URL('../data/knowledge-dictionary.json',import.meta.url)));
const modules=JSON.parse(readFileSync(new URL('../data/cms-learning.json',import.meta.url))).modules;
const index=buildCourseTranslationIndex(modules);
const terms=[...dictionary,...index.terms.filter(t=>!findTerm(dictionary,t.en))];
assert.equal(resolveTerm(terms,'grapes').entry.zh,'葡萄');
assert.equal(resolveTerm(terms,'Rootstocks.').entry.en,'Rootstock');
assert.equal(resolveTerm(terms,'Rootstocks.').form,true);
assert.equal(resolveTerm(terms,'leaves').entry.zh,'叶片');
assert.equal(resolveTerm(terms,'wine').entry.zh,'葡萄酒');
assert.equal(resolveTerm(terms,'lees').form,false);
assert.equal(resolveTerm(terms,'must I decant this wine?'),undefined);
assert.equal(resolveTerm(terms,'random_unknown_999'),undefined);
assert.equal(resolveTerm(terms,'Required'),undefined,'An editorial heading is not a translation');
assert(!index.terms.some(t=>t.en==='How'||t.en==='Chinese'));
assert(!termsInSelection(terms,'must I decant this wine?').some(t=>t.en.toLowerCase()==='must'));
assert(!termsInSelection(terms,'a research paper').some(t=>t.en.toLowerCase()==='arch'));
assert(index.passages.length>30);
const wine=index.passages.find(p=>p.en.startsWith('Wine is an alcoholic beverage'));
assert(wine&&wine.zh.includes('葡萄酒'));
assert.equal(readingTranslation(index.passages,wine.en).exact,true);
assert.equal(readingTranslation(index.passages,'grapes',wine.sectionId,wine.en).exact,false);
assert.equal(readingTranslation(index.passages,'grapes','unrelated',wine.en),undefined);
assert.equal(readingTranslation(index.passages,'grapes'),undefined);
for(const term of index.terms){assert(term.sources[0].url.startsWith('#cms-module?'));assert.equal(term.reviewedAt,'');assert(term.courseSource);}
console.log(`PASS: ${index.terms.length} course term pairs, ${index.passages.length} original bilingual passages; plural/diacritic lookup, context identity, no fabricated unknown or sentence translation.`);
