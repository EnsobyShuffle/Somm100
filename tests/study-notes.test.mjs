import assert from 'node:assert/strict';
import {loadTypeScript} from './load-typescript.mjs';
const {noteKey,saveStudyNote,readStudyNote,listStudyNotes,notesMarkdown}=await loadTypeScript('../lib/study-notes.ts');
const values=new Map();
const storage={getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v),get length(){return values.size},key:i=>[...values.keys()][i]??null};
const first={moduleId:'module01',moduleTitle:'Module 01',stage:1,resource:'core',sectionId:'M1-READ01',title:'First section',href:'#cms-module?module=module01&section=M1-READ01'};
const second={...first,sectionId:'M1-READ02',title:'Second section'};
const other={...first,moduleId:'module02'};
assert.equal(readStudyNote(storage,first),null);
saveStudyNote(storage,first,'第一节 · grapes');
saveStudyNote(storage,second,'第二节');
saveStudyNote(storage,other,'另一章');
saveStudyNote(storage,first,'重新编辑后的笔记');
assert.equal(readStudyNote(storage,first).body,'重新编辑后的笔记');
assert.equal(readStudyNote(storage,second).body,'第二节');
assert.equal(listStudyNotes(storage,'module01').notes.length,2);
assert.equal(listStudyNotes(storage,'module02').notes.length,1);
assert.notEqual(noteKey(first),noteKey({...first,stage:2}));
assert.notEqual(noteKey(first),noteKey({...first,resource:'expansion'}));
assert(notesMarkdown(listStudyNotes(storage,'module01').notes).includes('重新编辑后的笔记'));
assert.throws(()=>saveStudyNote(storage,first,'x'.repeat(20001)));
const original=values.get(noteKey(first));
assert.throws(()=>saveStudyNote({...storage,setItem:()=>{throw Error('quota')}},first,'should not overwrite'));
assert.equal(values.get(noteKey(first)),original);
values.set(noteKey(first),'{corrupt');
assert.throws(()=>readStudyNote(storage,first));
assert.throws(()=>saveStudyNote(storage,first,'must not overwrite corrupt data'));
assert.equal(values.get(noteKey(first)),'{corrupt');
assert.equal(listStudyNotes(storage,'module01').unreadable,1);
assert.equal(listStudyNotes(storage,'module01').notes.length,1);
console.log('PASS: notes persist and edit; module/section/stage/resource isolation; export; length/quota errors; unreadable originals preserved.');
